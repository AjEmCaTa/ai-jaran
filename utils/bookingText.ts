// Statusi se u bazi čuvaju na bosanskom; gost na engleskom vidi prevod.
const STATUS_EN: Record<string, string> = {
  'potvrđeno': 'Confirmed', 'na čekanju': 'Pending', 'na cekanju': 'Pending', 'otkazano': 'Cancelled',
  'završeno': 'Completed', 'isteklo': 'Expired', 'dogovor termina': 'Rescheduling',
};
export const statusText = (status: string, lang: Lang) => (lang === 'en' ? STATUS_EN[String(status).toLowerCase().trim()] || status : status);

const LANG_KEY = 'poslo_one_lang';

// Jezik: zapamćeni izbor, inače jezik preglednika (ex-YU jezici = bosanski, ostalo = engleski).
export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'bs' || saved === 'en') return saved;
  } catch {
    // bez spremanja
  }
  const nav = typeof navigator !== 'undefined' ? (navigator.languages?.[0] || navigator.language || '') : '';
  return /^(bs|hr|sr|sh|cnr|me|sl|mk)\b/i.test(nav) || nav === '' ? 'bs' : 'en';
}

export function saveLang(lang: Lang) {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    // bez spremanja
  }
}
